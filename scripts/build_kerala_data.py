#!/usr/bin/env python3
"""
Build the site's Kerala-wide data files from raw OpenStreetMap / Open-Meteo downloads.

Inputs (JSON files in the folder given as the first argument):
  kerala_rivers.json  {id: {name, km, main: [[lat, lon]...], extra: [[[lat, lon]...]...]}}
                      every named river in Kerala (Overpass: relation/way["waterway"="river"]
                      in area["ISO3166-2"="IN-KL"]), joined into source→mouth lines, ≥12 km
  kerala_dams.json    {official: {id: {lat, lon, name?, outlet?}}, others: [[name, lat, lon]...]}
                      dams in the official KSEB/Irrigation tables matched to OSM
                      (nwr["waterway"="dam"] / reservoirs), plus other named OSM dams
  kerala_places.json  [[name, lat, lon, kind]...]  node["place"~"city|town|village"]
  kerala_sites.json   [{river, km, lat, lon}...]   river-flow points: the GloFAS model cell
                      with the most flow near points every 20 km along each river
  kerala_water.json   [[outer ring, ...holes]...]  lakes, lagoons, reservoirs, river banks

Outputs: data/rivers.js, data/dams.js, data/places.js, data/sites.js, data/water.js
"""
import json, math, os, re, sys

SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), "..", "data")


def load(name):
    with open(os.path.join(SRC, name + ".json")) as f:
        return json.load(f)


def write(name, var, data, note):
    with open(os.path.join(OUT, name + ".js"), "w") as f:
        f.write("// " + note + "\n// Generated by scripts/build_kerala_data.py. Do not edit by hand.\n")
        f.write("window." + var + " = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print(f"wrote data/{name}.js ({os.path.getsize(os.path.join(OUT, name + '.js')) // 1024} KB)")


def km(a, b):
    k = math.cos(math.radians((a[0] + b[0]) / 2))
    return math.hypot(a[0] - b[0], (a[1] - b[1]) * k) * 111.2


rivers = load("kerala_rivers")
places = load("kerala_places")


def nearest_river(lat, lon, limit_km):
    best = None
    for rid, r in rivers.items():
        for p in r["main"]:
            d = km(p, (lat, lon))
            if best is None or d < best[1]:
                best = (rid, d)
    return best[0] if best and best[1] <= limit_km else None


def nearest_place(lat, lon, kinds="ctv", limit_km=12):
    best = None
    for name, plat, plon, kind in places:
        if kind not in kinds:
            continue
        d = km((plat, plon), (lat, lon))
        if best is None or d < best[1]:
            best = (name, d)
    return best[0] if best and best[1] <= limit_km else None


write("rivers", "RIVER_LINES", rivers, "Every named river in Kerala from OpenStreetMap (© OpenStreetMap contributors, ODbL), source → mouth, simplified to ~150 m.")
write("places", "KERALA_PLACES", places, "Cities (c), towns (t) and villages (v) in Kerala from OpenStreetMap (© OpenStreetMap contributors, ODbL): [name, lat, lon, kind].")

dams = load("kerala_dams")
official = {}
for did, d in dams["official"].items():
    d = dict(d)
    if not d.get("outlet"):
        d["river"] = nearest_river(d["lat"], d["lon"], 8.0)
    official[did] = d
# Other named dams: skip regulator-cum-bridges and small stream structures.
skip = re.compile(r"\b(rcb|swecb|regulator|thodu|bund|anicut)\b", re.I)
others = [o for o in dams["others"] if not skip.search(o[0])]
write("dams", "DAM_LOCATIONS", official, "Positions of the dams in the official KSEB / Irrigation tables, matched to OpenStreetMap (© OpenStreetMap contributors).")
with open(os.path.join(OUT, "dams.js"), "a") as f:
    f.write("// Other named dams in OpenStreetMap (no official daily reading): [name, lat, lon].\n")
    f.write("window.OTHER_DAMS = " + json.dumps(others, separators=(",", ":"), ensure_ascii=False) + ";\n")
print(f"  {len(official)} official dams ({sum(1 for d in official.values() if d.get('river'))} on a river line), {len(others)} other dams")

if os.path.exists(os.path.join(SRC, "kerala_sites.json")):
    sites, seen = [], set()
    for s in load("kerala_sites"):
        key = (round(s["lat"], 3), round(s["lon"], 3))
        if key in seen:
            continue
        seen.add(key)
        town = nearest_place(s["lat"], s["lon"], "ct", 15) or nearest_place(s["lat"], s["lon"], "ctv", 15)
        rname = rivers[s["river"]]["name"]
        sites.append({"id": f"{s['river']}-{s['km']}", "river": s["river"], "lat": s["lat"], "lon": s["lon"],
                      "name": rname + (" near " + town if town else " (" + str(s["km"]) + " km from its source)"), "town": town or rname})
    write("sites", "FLOW_SITES", sites, "River-flow points: the GloFAS model cell (Open-Meteo) with the most flow near points every 20 km along each river.")

if os.path.exists(os.path.join(SRC, "kerala_water.json")):
    write("water", "WATER_AREAS", load("kerala_water"), "Water areas in Kerala from OpenStreetMap (© OpenStreetMap contributors, ODbL): lakes, lagoons, reservoirs and river banks, simplified. Each polygon is [outer ring, ...island holes].")
