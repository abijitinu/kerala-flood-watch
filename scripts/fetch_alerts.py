#!/usr/bin/env python3
"""
Fetch Kerala's active official disaster alerts and write data/alerts.js for the website.

Source: SACHET, the National Disaster Management Authority's Common Alerting Protocol (CAP)
portal (https://sachet.ndma.gov.in). Alerts from IMD Thiruvananthapuram and the Kerala State
Disaster Management Authority are published there, in English and Malayalam. The Kerala RSS
feed lists recent alerts; each links to a CAP message with its severity, validity and text.

Districts are read from the alert text (the CAP area polygons aren't publicly downloadable).
An alert that names no district is treated as covering the whole state.

    python3 scripts/fetch_alerts.py
"""
import datetime as dt
import json
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

RSS = "https://sachet.ndma.gov.in/cap_public_website/rss/rss_kerala.xml"
OUT = os.path.join(os.path.dirname(__file__), "..", "data", "alerts.js")
DISTRICTS = os.path.join(os.path.dirname(__file__), "..", "data", "districts.js")
UA = {"User-Agent": "Mozilla/5.0 (KeralaFloodWatch alert fetcher)"}
CAP = {"cap": "urn:oasis:names:tc:emergency:cap:1.2"}
# CAP severity on SACHET's colour scale (the same four colours IMD uses).
LEVEL = {"Extreme": "red", "Severe": "orange", "Moderate": "yellow", "Minor": "green"}


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read()


def district_names():
    """Read the district list (and the spellings alerts use) from data/districts.js."""
    text = open(DISTRICTS, encoding="utf-8").read()
    return {m.group(1): json.loads("[" + m.group(2) + "]") for m in re.finditer(r'^\s*(\w+):\s*\{.*?aka: \[(.*?)\]', text, re.M)}


def districts_in(text, names):
    found = []
    for key, aka in names.items():
        for a in aka:
            # Abbreviations (TVM, EKM…) only count in capitals, so "alp" inside a word doesn't match.
            pattern = (r"\b" + a.upper() + r"\b") if len(a) <= 4 else re.escape(a)
            if re.search(pattern, text, 0 if len(a) <= 4 else re.I):
                found.append(key)
                break
    return found


def main():
    names = district_names()
    now = dt.datetime.now(dt.timezone.utc)
    rss = ET.fromstring(get(RSS))
    alerts, seen = [], set()
    for item in rss.iter("item"):
        link = item.findtext("link")
        try:
            cap = ET.fromstring(get(link))
        except Exception as e:  # one bad message shouldn't stop the rest
            print("skip", link, e, file=sys.stderr)
            continue
        if cap.findtext("cap:status", namespaces=CAP) != "Actual" or cap.findtext("cap:msgType", namespaces=CAP) == "Cancel":
            continue
        infos = {(i.findtext("cap:language", namespaces=CAP) or "").lower()[:2]: i for i in cap.findall("cap:info", CAP)}
        en = infos["en"] if "en" in infos else next(iter(infos.values()), None)
        if en is None:
            continue
        ml = infos.get("ml")
        expires = en.findtext("cap:expires", namespaces=CAP)
        if not expires or dt.datetime.fromisoformat(expires) < now:
            continue
        head_en = (en.findtext("cap:headline", namespaces=CAP) or "").strip()
        head_ml = (ml.findtext("cap:headline", namespaces=CAP) or "").strip() if ml is not None else ""
        key = (head_en, expires)
        if key in seen:
            continue
        seen.add(key)
        districts = districts_in(head_en + " " + head_ml, names)
        severity = en.findtext("cap:severity", namespaces=CAP) or ""
        alerts.append({
            "id": item.findtext("guid"),
            "event": en.findtext("cap:event", namespaces=CAP),
            "severity": severity,
            "level": LEVEL.get(severity, "yellow"),
            "en": head_en,
            "ml": head_ml or head_en,
            "from": en.findtext("cap:effective", namespaces=CAP) or cap.findtext("cap:sent", namespaces=CAP),
            "expires": expires,
            "source": (item.findtext("author") or "").split("(")[-1].rstrip(")") or cap.findtext("cap:sender", namespaces=CAP),
            "districts": districts,
            "statewide": not districts,
        })
    order = {"red": 0, "orange": 1, "yellow": 2, "green": 3}
    alerts.sort(key=lambda a: (order[a["level"]], a["expires"]))
    data = {"fetchedAt": now.isoformat(timespec="seconds"), "source": "https://sachet.ndma.gov.in", "alerts": alerts}
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/fetch_alerts.py from SACHET (NDMA). Do not edit by hand.\n")
        f.write("window.OFFICIAL_ALERTS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    os.replace(tmp, OUT)
    print(f"{len(alerts)} active alerts written to data/alerts.js")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        # Keep the previous file: the site shows its time, so an old file is visible as old.
        print("Alert fetch failed:", e, file=sys.stderr)
        sys.exit(1)
